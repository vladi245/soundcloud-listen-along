import {
  cp,
  lstat,
  mkdir,
  readdir,
  readFile,
  realpath,
  rm,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(import.meta.dirname, '..');
const target = process.argv[2] ? path.resolve(process.argv[2]) : null;

if (
  !target ||
  path.basename(target) !== 'soundcloud-listen-along-server' ||
  !target.startsWith('/tmp/opencode/')
) {
  throw new Error(
    'Target must be /tmp/opencode/.../soundcloud-listen-along-server',
  );
}

await mkdir(target, { recursive: true });
if ((await lstat(target)).isSymbolicLink()) {
  throw new Error('Target must not be a symbolic link');
}
const relativeParent = path.relative(
  '/tmp/opencode',
  await realpath(path.dirname(target)),
);
if (relativeParent.startsWith('..') || path.isAbsolute(relativeParent)) {
  throw new Error('Target parent resolves outside /tmp/opencode');
}
const existing = await readdir(target);
const owned =
  existing.every((entry) => entry === '.git') ||
  existing.includes('.server-template-export') ||
  existing.includes('.upstream-revision');
if (!owned) {
  throw new Error('Target is not empty and has no server-template marker');
}

const staging = path.join(
  path.dirname(target),
  '.soundcloud-listen-along-server-export',
);
await rm(staging, { recursive: true, force: true });
await mkdir(path.join(staging, '.github/workflows'), { recursive: true });
await mkdir(path.join(staging, 'lib'), { recursive: true });
await mkdir(path.join(staging, 'server/src'), { recursive: true });

const copy = (source, destination = source) =>
  cp(path.join(root, source), path.join(staging, destination), {
    recursive: true,
  });

await Promise.all([
  copy('prettier.config.mjs'),
  copy('LICENSE'),
  copy('lib/backend.ts'),
  copy('lib/protocol.ts'),
  copy('server/.dev.vars.example', '.dev.vars.example'),
  copy('server/package-lock.json', 'package-lock.json'),
  copy('server/src', 'server/src'),
  copy('server/vitest.config.ts', 'vitest.config.ts'),
]);

const privacy = (await readFile(path.join(root, 'docs/privacy.md'), 'utf8'))
  .replace('open-source extension', 'browser extension')
  .replace(
    'These are engineering and transparency guidelines, not legal advice. See [compliance](compliance.md).',
    'These are engineering and transparency guidelines, not legal advice.',
  );
await writeFile(path.join(staging, 'PRIVACY.md'), privacy);

const packageJson = JSON.parse(
  await readFile(path.join(root, 'server/package.json'), 'utf8'),
);
packageJson.description =
  'Self-hosted Cloudflare Durable Objects backend for SoundCloud Listen Along.';
packageJson.cloudflare = {
  bindings: {
    ROOM_CREATION_KEY: {
      description:
        'Paste the random room creation key generated by the extension. Keep it private.',
    },
  },
};
await writeFile(
  path.join(staging, 'package.json'),
  `${JSON.stringify(packageJson, null, 2)}\n`,
);

const tsconfig = JSON.parse(
  await readFile(path.join(root, 'server/tsconfig.json'), 'utf8'),
);
tsconfig.include = ['server/src/**/*.ts', 'lib/*.ts', 'vitest.config.ts'];
await writeFile(
  path.join(staging, 'tsconfig.json'),
  `${JSON.stringify(tsconfig, null, 2)}\n`,
);

const wrangler = (
  await readFile(path.join(root, 'server/wrangler.toml'), 'utf8')
).replace('main = "src/index.ts"', 'main = "server/src/index.ts"');
await writeFile(path.join(staging, 'wrangler.toml'), wrangler);
await writeFile(path.join(staging, '.server-template-export'), 'generated\n');
await writeFile(
  path.join(staging, '.gitignore'),
  'node_modules/\n.dev.vars\n.wrangler/\ncoverage/\n',
);
await writeFile(
  path.join(staging, '.github/workflows/ci.yml'),
  `name: CI

on:
  push:
    branches: [main]
  pull_request:

permissions:
  contents: read

jobs:
  verify:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v5
      - uses: actions/setup-node@v5
        with:
          node-version: 22
          cache: npm
      - run: npm ci
      - run: npm run typecheck
      - run: npm test
      - run: npx wrangler deploy --dry-run
`,
);
await writeFile(
  path.join(staging, 'README.md'),
  `# SoundCloud Listen Along Server

Self-hosted Cloudflare Worker and Durable Objects backend for the unofficial SoundCloud Listen Along browser extension.

[![Deploy to Cloudflare](https://deploy.workers.cloudflare.com/button)](https://deploy.workers.cloudflare.com/?url=https://github.com/vladi245/soundcloud-listen-along-server)

## Deploy

1. Select **Deploy to Cloudflare** and sign in to your Cloudflare account.
2. Keep the generated Worker and Durable Object settings.
3. Paste the random key shown by the extension into \`ROOM_CREATION_KEY\`.
4. Deploy and copy the resulting \`https://...workers.dev\` address into the extension.

The deployment creates one Durable Object per room and a separate creation-rate limiter. It does not create a project-operated relay, directory, analytics endpoint, or account system.

## Local verification

Requires Node.js 22 or newer.

\`\`\`sh
npm ci
npm run typecheck
npm test
npx wrangler deploy --dry-run
\`\`\`

For local development, copy \`.dev.vars.example\` to \`.dev.vars\`, replace the example key, and run \`npm run dev\`.

## Security and privacy

- Treat \`ROOM_CREATION_KEY\`, room codes, and host tokens as credentials.
- Audio remains on SoundCloud; the backend relays track URLs and playback synchronization data only.
- Rooms expire automatically, and room creation is rate limited without storing client IP addresses in application storage.
- Cloudflare account logs and retention remain the deploying operator's responsibility.

The extension's public [privacy policy](PRIVACY.md) describes its local and backend data handling.

This repository is an automatically exported deployment subset and contains no extension code or credentials.

Released under the [MIT License](LICENSE). This project is independent and is not affiliated with or endorsed by SoundCloud.
`,
);

await Promise.all(
  existing
    .filter((entry) => entry !== '.git')
    .map((entry) =>
      rm(path.join(target, entry), { recursive: true, force: true }),
    ),
);
await Promise.all(
  (await readdir(staging)).map((entry) =>
    cp(path.join(staging, entry), path.join(target, entry), {
      recursive: true,
    }),
  ),
);
await rm(staging, { recursive: true, force: true });
